from rest_framework import viewsets, status, permissions, generics
from rest_framework.decorators import action
from rest_framework.response import Response
from drf_yasg.utils import swagger_auto_schema
from drf_yasg import openapi

from .models import Notification, DeviceToken
from .serializers import (
    NotificationSerializer, 
    DeviceTokenSerializer, 
    DeviceTokenUnregisterSerializer,
    TestPushNotificationSerializer
)

class NotificationViewSet(viewsets.ModelViewSet):
    serializer_class = NotificationSerializer
    permission_classes = [permissions.IsAuthenticated]

    def get_queryset(self):
        if getattr(self, 'swagger_fake_view', False):
            return Notification.objects.none()
        
        queryset = Notification.objects.filter(recipient=self.request.user).exclude(
            sender__is_deleted=True
        ).exclude(
            sender__is_active=False
        )
        
        notification_type = self.request.query_params.get('notification_type')
        is_read_param = self.request.query_params.get('is_read')

        if notification_type:
            queryset = queryset.filter(notification_type=notification_type)
        if is_read_param is not None:
            if is_read_param.lower() in ['true', '1']:
                queryset = queryset.filter(is_read=True)
            elif is_read_param.lower() in ['false', '0']:
                queryset = queryset.filter(is_read=False)

        return queryset

    @swagger_auto_schema(
        manual_parameters=[
            openapi.Parameter('notification_type', openapi.IN_QUERY, description="Filter by type (message, saved_listing, inquiry, review, system)", type=openapi.TYPE_STRING),
            openapi.Parameter('is_read', openapi.IN_QUERY, description="Filter by read status (true / false)", type=openapi.TYPE_BOOLEAN),
        ]
    )
    def list(self, request, *args, **kwargs):
        return super().list(request, *args, **kwargs)

    @action(detail=False, methods=['get'], url_path='unread-count')
    def unread_count(self, request):
        count = Notification.objects.filter(
            recipient=request.user, 
            is_read=False
        ).exclude(
            sender__is_deleted=True
        ).exclude(
            sender__is_active=False
        ).count()
        return Response({"unread_count": count}, status=status.HTTP_200_OK)

    @action(detail=True, methods=['patch'], url_path='read')
    def mark_as_read(self, request, pk=None):
        notification = self.get_object()
        notification.is_read = True
        notification.save()
        serializer = self.get_serializer(notification)
        return Response(serializer.data, status=status.HTTP_200_OK)

    @action(detail=False, methods=['post'], url_path='read-all')
    def read_all(self, request):
        Notification.objects.filter(recipient=request.user, is_read=False).update(is_read=True)
        return Response({"message": "All notifications marked as read."}, status=status.HTTP_200_OK)


class DeviceTokenView(generics.GenericAPIView):
    serializer_class = DeviceTokenSerializer
    permission_classes = [permissions.IsAuthenticated]

    @swagger_auto_schema(
        operation_summary="Register or Refresh Device FCM Token",
        operation_description=(
            "Registers an FCM device token for the authenticated user to receive push notifications.\n\n"
            "- **token**: The registration token generated by Firebase SDK on the mobile phone (`FirebaseMessaging.instance.getToken()`).\n"
            "- **platform**: 'android', 'ios', or 'web' (default: 'android').\n\n"
            "If the token already exists, it is reactivated and associated with this user."
        ),
        request_body=DeviceTokenSerializer,
        responses={200: DeviceTokenSerializer, 201: DeviceTokenSerializer}
    )
    def post(self, request, *args, **kwargs):
        serializer = self.get_serializer(data=request.data)
        serializer.is_valid(raise_exception=True)
        device_token = serializer.save()
        return Response(DeviceTokenSerializer(device_token).data, status=status.HTTP_200_OK)

    @swagger_auto_schema(
        operation_summary="Unregister/Deactivate Device FCM Token (Logout)",
        operation_description=(
            "Deactivates a device's FCM token so push notifications (chats, bookings, property alerts) "
            "are no longer sent to this phone after the user logs out."
        ),
        request_body=DeviceTokenUnregisterSerializer,
        responses={200: openapi.Response(description="Device token deactivated successfully")}
    )
    def delete(self, request, *args, **kwargs):
        serializer = DeviceTokenUnregisterSerializer(data=request.data)
        serializer.is_valid(raise_exception=True)
        token = serializer.validated_data['token']
        DeviceToken.objects.filter(user=request.user, token=token).update(is_active=False)
        return Response({"message": "Device token deactivated successfully."}, status=status.HTTP_200_OK)


class TestPushNotificationView(generics.GenericAPIView):
    """
    Test endpoint for frontend developers to send an immediate push notification to their device.
    """
    serializer_class = TestPushNotificationSerializer
    permission_classes = [permissions.IsAuthenticated]

    @swagger_auto_schema(
        operation_summary="Send Test Push Notification to Device",
        operation_description=(
            "Sends an immediate test push notification to the authenticated user's registered devices.\n\n"
            "- **title**: Custom notification title (optional, defaults to 'Box-4 Test Notification').\n"
            "- **body**: Custom message body (optional, defaults to 'This is a test push notification from Box-4 backend.').\n"
            "- **data**: Optional key-value dictionary to test custom payload handling in the mobile app.\n"
            "- **token**: Optional specific FCM device token to target directly without registering first.\n\n"
            "Use this endpoint to confirm that push notifications appear on your mobile phone."
        ),
        request_body=TestPushNotificationSerializer,
        responses={200: openapi.Response(description="Test notification dispatch results")}
    )
    def post(self, request, *args, **kwargs):
        serializer = self.get_serializer(data=request.data)
        serializer.is_valid(raise_exception=True)

        title = serializer.validated_data.get('title') or "Box-4 Test Notification"
        body = serializer.validated_data.get('body') or "This is a test push notification from Box-4 backend."
        custom_data = serializer.validated_data.get('data') or {"type": "test_push", "sender": "Box-4 Server"}
        specific_token = serializer.validated_data.get('token')

        from core.firebase import is_firebase_configured, send_push_notification

        if specific_token:
            DeviceToken.objects.update_or_create(
                token=specific_token,
                defaults={'user': request.user, 'is_active': True}
            )

        active_tokens = list(DeviceToken.objects.filter(user=request.user, is_active=True).values_list('token', flat=True))

        firebase_ready = is_firebase_configured()
        sent_count = send_push_notification(
            user=request.user,
            title=title,
            body=body,
            data=custom_data
        )

        return Response({
            "firebase_configured": firebase_ready,
            "registered_tokens_count": len(active_tokens),
            "tokens": [t[:15] + "..." for t in active_tokens],
            "sent_count": sent_count,
            "message": (
                f"Successfully dispatched push notification to {sent_count} device(s)."
                if sent_count > 0 else (
                    "Firebase Admin SDK is not configured yet (needs a Service Account private key JSON in the firebase/ folder)."
                    if not firebase_ready else "No active device tokens found for this user. Please register a device token first via POST /api/v1/notifications/devices/."
                )
            )
        }, status=status.HTTP_200_OK)

